// The ONE command template set (SPEC §2). Every harness's command files are rendered from this list
// by render.ts. Bodies use only `$ARGUMENTS` and name tools by short name plus server.
import { JOIN_INSTRUCTION } from '../core/notice.js'

export interface CommandTemplate {
    name: string
    description: string
    argumentHint: string | null
    body: string
}

const SERVER = 'the harness-summit MCP server'
const tool = (name: string) => `the \`${name}\` tool of ${SERVER}`

// Purpose: the rule for a trailing `--force` in the user text (takes a name over from a holder that is
// not alive now); `what` names the argument the flag is removed from.
const forceRule = (what: string) =>
    `If that text ends with \`--force\`, remove \`--force\` from the ${what} and also pass \`force\` set to true.`

const JOIN_BODY = [
    `Call ${tool('summit_join')} with no arguments.`,
    `The user text after the command is: \`$ARGUMENTS\`. If it is not empty, use it as a display name: call ${tool('summit_rename')} with \`name\` set to that text. ${forceRule('name')}`,
    'Report the result in one short line: uuid, name and group.',
    JOIN_INSTRUCTION,
].join('\n\n')

const GROUP_BODY = [
    `Call ${tool('summit_group')} with \`name\` set to the user text after the command: \`$ARGUMENTS\`. ${forceRule('group name')}`,
    'Report the new group in one short line.',
].join('\n\n')

const RENAME_BODY = [
    `Call ${tool('summit_rename')} with \`name\` set to the user text after the command: \`$ARGUMENTS\`. ${forceRule('name')}`,
    'Report the new name in one short line.',
].join('\n\n')

const SEND_BODY = [
    'The user text after the command is: `$ARGUMENTS`.',
    'Its first word is the receiver (`@name`, `name` or a uuid). The rest is the message.',
    `Call ${tool('summit_send')} with \`to\` set to the receiver and \`message\` set to the message, unchanged.`,
    'Report the message id and the wake result in one short line.',
].join('\n\n')

const LIST_BODY = [
    `Call ${tool('summit_members')} with no arguments. Ignore any text the user typed after the command.`,
    'Show the group key in one line, then the members as a short table with the columns name, harness, alive and uuid (its first 8 characters). Write `(you)` after the name of the member whose `self` is true. Show a missing name as `-`.',
].join('\n\n')

const BYE_BODY = [
    `Call ${tool('summit_bye')} with no arguments.`,
    'Report in one short line exactly what the result says was removed.',
].join('\n\n')

const JOIN = { description: 'Join the harness-summit group of this project', argumentHint: '[name]', body: JOIN_BODY }
const GROUP = {
    description: 'Move to a named harness-summit group',
    argumentHint: '<group> [--force]',
    body: GROUP_BODY,
}
const RENAME = {
    description: 'Set your harness-summit display name',
    argumentHint: '<name> [--force]',
    body: RENAME_BODY,
}
const LIST = { description: 'List the members of your harness-summit group', argumentHint: null, body: LIST_BODY }

export const COMMANDS: CommandTemplate[] = [
    { name: 'summit-join', ...JOIN },
    { name: 'sj', ...JOIN },
    { name: 'summit-group', ...GROUP },
    { name: 'sg', ...GROUP },
    { name: 'summit-rename', ...RENAME },
    { name: 'sr', ...RENAME },
    { name: 'summit-list', ...LIST },
    { name: 'sl', ...LIST },
    {
        name: 'summit-send',
        description: 'Send a message to another agent',
        argumentHint: '@<name or uuid> <message>',
        body: SEND_BODY,
    },
    { name: 'summit-bye', description: 'Leave harness-summit', argumentHint: null, body: BYE_BODY },
]

// Marker line in every generated file; install uses it to recognise its own files.
export const GENERATED_MARKER =
    '<!-- generated by harness-summit; edits are overwritten by `harness-summit install` -->'
